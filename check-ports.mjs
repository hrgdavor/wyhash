// Checks that every port of this project produces the value the *reference* produces — not that they agree with
// each other, which they could do while all being wrong.
//
//   1. REFERENCE INTEGRITY — re-run `conformance/gen-vectors.zig` and compare its output with the two committed
//      artefacts: `conformance/wyhash-vectors.json` (what the JavaScript and Zig ports parse) and
//      `src/test/java/hr/hrg/wyhash/WyhashVectors.java` (the generated table the Java port asserts, because Java
//      has no JSON reader and this library takes no dependency to borrow one). If a Zig upgrade ever changes
//      `std.hash.Wyhash`, the committed vectors become a description of yesterday's algorithm and every port that
//      "passes" is passing against nothing — so both artefacts are diffed.
//   2. THE JAVASCRIPT PORT — every case and every seed case, with the library-produced golden vectors asserted
//      first.
//   3. THE JAVA PORT — compile the implementation, the generated table and the self-checking vector runner with
//      plain `javac`/`java` (no Maven, no JUnit) and run it: every case through `byte[]`, through
//      `MemorySegment`, and through the streaming form.
//   4. THE ZIG PORT — `zig test tests.zig`, which asserts the same file from the reference's own language.
//
//   bun check-ports.mjs [--allow-missing-zig]
//
// The toolchains are **resolved and version-checked** rather than taken from whatever `PATH` happens to hold: the
// Zig sources are written for 0.17+, and the `MemorySegment` path needs a JDK 22+ (`java.lang.foreign`). A
// reference generated by the wrong Zig release is exactly what this script exists to catch. Overrides:
// `WYHASH_ZIG`, `WYHASH_JDK` (or `JAVA_HOME`), and `ZIG`, the variable Zig's own tooling reads.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const started = performance.now();
const allowMissingZig = process.argv.includes('--allow-missing-zig');
const REQUIRED_ZIG = '0.17';
const REQUIRED_JAVA = 22;

const exe = (name) => (process.platform === 'win32' ? `${name}.exe` : name);

let passed = 0;
let failed = 0;
const check = (name, condition, detail = '') => {
  if (condition) {
    passed++;
    console.log(`ok   ${name}`);
  } else {
    failed++;
    console.log(`FAIL ${name}${detail ? ` — ${detail}` : ''}`);
  }
};

const run = (command, args, options = {}) => spawnSync(command, args, { encoding: 'utf8', ...options });

/** Whether `found` (major.minor) is at least `required`. */
function atLeast(found, required) {
  if (!found) return false;
  const [major, minor] = found.split('.').map((part) => Number.parseInt(part, 10));
  const [wantMajor, wantMinor] = required.split('.').map((part) => Number.parseInt(part, 10));
  return major > wantMajor || (major === wantMajor && minor >= wantMinor);
}

// ------------------------------------------------------------------ toolchains

function zigCandidates() {
  const candidates = [];
  for (const variable of ['WYHASH_ZIG', 'ZIG']) {
    if (process.env[variable]) candidates.push([process.env[variable], variable]);
  }
  // A directory of releases, one per version, as this machine keeps them (newest first).
  for (const root of ['D:\\wrk\\zig', join(process.env.USERPROFILE ?? process.env.HOME ?? '', 'zig')]) {
    if (!existsSync(root)) continue;
    let releases = [];
    try {
      releases = readdirSync(root).sort((left, right) => Number.parseInt(right, 10) - Number.parseInt(left, 10));
    } catch {
      continue;
    }
    for (const release of releases) candidates.push([join(root, release, exe('zig')), `${root}\\${release}`]);
  }
  candidates.push(['zig', 'PATH']);
  return candidates;
}

function resolveZig() {
  const tried = [];
  for (const [command, source] of zigCandidates()) {
    if (command.includes('\\') && !existsSync(command)) continue;
    const result = run(command, ['version']);
    const match = `${result.stdout}${result.stderr}`.match(/(\d+)\.(\d+)/);
    const version = result.status === 0 && match ? `${match[1]}.${match[2]}` : null;
    if (version === null) {
      tried.push(`${command} (${source}: could not read its version)`);
      continue;
    }
    if (!atLeast(version, REQUIRED_ZIG)) {
      tried.push(`${command} (${source}: Zig ${version}, needs ${REQUIRED_ZIG}+)`);
      continue;
    }
    return { command, version, source };
  }
  throw new Error(`no Zig ${REQUIRED_ZIG}+ found. Tried:\n  ${tried.join('\n  ')}\n`
    + `Set WYHASH_ZIG to a Zig ${REQUIRED_ZIG} executable (for example D:\\wrk\\zig\\17\\zig.exe).`);
}

function resolveJava() {
  const tried = [];
  const accept = (home, source) => {
    const java = join(home, 'bin', exe('java'));
    if (!existsSync(java)) {
      tried.push(`${java} (${source}: no java there)`);
      return null;
    }
    const result = run(java, ['-version']);
    const match = `${result.stderr}${result.stdout}`.match(/version "(\d+)/);
    const major = match ? Number.parseInt(match[1], 10) : null;
    if (major === null) {
      tried.push(`${java} (${source}: could not read its version)`);
      return null;
    }
    if (major < REQUIRED_JAVA) {
      tried.push(`${java} (${source}: Java ${major}, needs ${REQUIRED_JAVA}+ for java.lang.foreign)`);
      return null;
    }
    return { java, javac: join(home, 'bin', exe('javac')), version: major, source };
  };

  const homes = [];
  if (process.env.WYHASH_JDK) homes.push([process.env.WYHASH_JDK, 'WYHASH_JDK']);
  if (process.env.JAVA_HOME) homes.push([process.env.JAVA_HOME, 'JAVA_HOME']);
  for (const [home, source] of homes) {
    const found = accept(home, source);
    if (found) return found;
  }

  // The installed JDKs, newest first. `JAVA_HOME` on a developer machine is often an older release — and the
  // stock Windows `java` on `PATH` is older still — so a version-checked scan is what lets this script run
  // without the caller having to know which JDK it needs, the same shape as the Zig resolver below.
  const roots = [
    'C:\\Program Files\\Java',
    'C:\\Program Files\\Eclipse Adoptium',
    'C:\\Program Files\\Microsoft',
    'C:\\Program Files\\Zulu',
    'C:\\Program Files\\Amazon Corretto',
    join(process.env.USERPROFILE ?? process.env.HOME ?? '', '.jdks'),
    '/usr/lib/jvm',
    '/Library/Java/JavaVirtualMachines',
  ];
  const candidates = [];
  for (const root of roots) {
    if (!existsSync(root)) continue;
    let entries = [];
    try {
      entries = readdirSync(root);
    } catch {
      continue;
    }
    for (const entry of entries) {
      // `jdk-25`, `jdk-22.0.1`, `temurin-25-jdk`, `zulu-25`, `corretto-25`: the first number in the directory
      // name is the major, and that is what decides the order.
      const major = /\d+/.exec(entry.replace(/^[a-z-]*/i, ''))?.[0];
      if (major) candidates.push([Number.parseInt(major, 10), join(root, entry), `${root}\\${entry}`]);
    }
  }
  candidates.sort((left, right) => right[0] - left[0]);
  for (const [, home, source] of candidates) {
    const found = accept(home, source);
    if (found) return found;
  }

  // `java` from the PATH, under the same version rule.
  const onPath = run(exe('java'), ['-version']);
  const match = `${onPath.stderr}${onPath.stdout}`.match(/version "(\d+)/);
  const major = match ? Number.parseInt(match[1], 10) : null;
  if (major !== null && major >= REQUIRED_JAVA) {
    return { java: exe('java'), javac: exe('javac'), version: major, source: 'PATH' };
  }
  tried.push(`${exe('java')} (PATH: ${major === null ? 'not found' : `Java ${major}`})`);
  throw new Error(`no JDK ${REQUIRED_JAVA}+ found. Tried:\n  ${tried.join('\n  ')}\n`
    + `Set JAVA_HOME or WYHASH_JDK to a JDK ${REQUIRED_JAVA}+ home.`);
}

const zigArgs = ['--cache-dir', join(here, '.zig-cache', 'local'), '--global-cache-dir', join(here, '.zig-cache', 'global')];
const vectorsPath = join(here, 'conformance', 'wyhash-vectors.json');
const vectorsText = readFileSync(vectorsPath, 'utf8');
const vectors = JSON.parse(vectorsText);
const javaVectorsPath = join(here, 'src', 'test', 'java', 'hr', 'hrg', 'wyhash', 'WyhashVectors.java');

let zig = null;
try {
  zig = resolveZig();
  console.log(`zig  ${zig.version} (${zig.source})`);
} catch (missing) {
  check('a Zig toolchain is available', allowMissingZig,
    `${missing.message}\n      (pass --allow-missing-zig to warn instead of fail)`);
}

const java = resolveJava();
console.log(`java ${java.version} (${java.source})`);

// ------------------------------------------------------------------ 1. the reference

if (zig !== null) {
  const generate = (mode) => run(zig.command, ['run', join('conformance', 'gen-vectors.zig'), ...zigArgs, ...mode], { cwd: here });

  const generated = generate([]);
  check('the reference generator runs', generated.status === 0, generated.stderr?.trim());
  if (generated.status === 0) {
    const same = generated.stdout === vectorsText;
    let detail = '';
    if (!same) {
      const expected = vectorsText.split('\n');
      const actual = generated.stdout.split('\n');
      const at = expected.findIndex((line, index) => line !== actual[index]);
      detail = at < 0
        ? `the files differ in length: committed ${expected.length} lines, generated ${actual.length}`
        : `first difference at line ${at + 1}:\n      committed: ${expected[at]}\n      generated: ${actual[at]}`;
    }
    check("the committed JSON vectors are the reference's output", same, detail);
  }

  const generatedJava = generate(['--', 'java']);
  check('the reference generator runs in its java mode', generatedJava.status === 0, generatedJava.stderr?.trim());
  if (generatedJava.status === 0) {
    const committed = readFileSync(javaVectorsPath, 'utf8');
    check("the committed Java table is the reference's output", generatedJava.stdout === committed,
      generatedJava.stdout === committed
        ? ''
        : 'regenerate with: zig run conformance/gen-vectors.zig -- java > src/test/java/hr/hrg/wyhash/WyhashVectors.java');
  }
}

// ------------------------------------------------------------------ 2. the JavaScript port

const js = await import('./js/wyhash64.mjs');
check('the library-produced golden vectors', js.assertLibraryGoldenVectors() === 7);

let jsCases = 0;
for (const vector of vectors.cases) {
  const bytes = vector.text !== undefined ? Buffer.from(vector.text, 'utf8') : js.patternBytes(vector.pattern.length);
  const actual = js.wyhash64Hex(bytes);
  if (actual !== vector.wyhash64) check(`js: ${vector.label}`, false, `got ${actual}, vectors say ${vector.wyhash64}`);
  jsCases++;
}
check(`js: ${jsCases} case(s) match the reference`, true);

let seedCases = 0;
for (const vector of vectors.seedCases) {
  const actual = js.wyhash64Hex(Buffer.from(vector.text, 'utf8'), BigInt(`0x${vector.seed}`));
  if (actual !== vector.wyhash64) check(`js, seeded: ${vector.label}`, false, `got ${actual}, vectors say ${vector.wyhash64}`);
  seedCases++;
}
check(`js: ${seedCases} seeded case(s) match the reference`, true);

// ------------------------------------------------------------------ 3. the Java port

const javaClasses = join(here, '.java-check');
rmSync(javaClasses, { recursive: true, force: true });
mkdirSync(javaClasses, { recursive: true });
const sources = [
  join(here, 'src', 'main', 'java', 'hr', 'hrg', 'wyhash', 'Wyhash64.java'),
  join(here, 'src', 'test', 'java', 'hr', 'hrg', 'wyhash', 'WyhashVectors.java'),
  join(here, 'src', 'test', 'java', 'hr', 'hrg', 'wyhash', 'WyhashVectorCheck.java'),
];
const compiled = run(java.javac, ['-d', javaClasses, ...sources]);
check('java: the port compiles (javac, no dependencies)', compiled.status === 0,
  (compiled.stderr || '').trim().split('\n').slice(0, 6).join('\n      '));
if (compiled.status === 0) {
  const checked = run(java.java, ['-cp', javaClasses, 'hr.hrg.wyhash.WyhashVectorCheck']);
  check('java: every reference case, segment and streaming paths included', checked.status === 0,
    (checked.stderr || checked.stdout || '').trim());
  if (checked.status === 0) console.log(`     ${checked.stdout.trim()}`);
}
rmSync(javaClasses, { recursive: true, force: true });

// ------------------------------------------------------------------ 4. the Zig port

if (zig !== null) {
  const test = run(zig.command, ['test', 'tests.zig', ...zigArgs], { cwd: here });
  check('zig: the port passes the same vectors', test.status === 0,
    (test.stderr || test.stdout || '').trim().split('\n').slice(-6).join('\n      '));
}

console.log('');
console.log(`${passed} passed, ${failed} failed`);
console.log(`checked in ${Math.round(performance.now() - started)}ms${zig === null ? ' (without Zig: reference integrity and the Zig port were not checked)' : ''}`);
process.exit(failed === 0 ? 0 : 1);